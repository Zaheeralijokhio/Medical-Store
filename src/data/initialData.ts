export function sanitizeStaffAccounts(users?: User[]): User[] {
  if (!Array.isArray(users) || users.length === 0) {
    return [OWNER_ACCOUNT];
  }

  // Remove old pre-seeded demo accounts, keep Dr. Abdul Rehman & any staff created by Dr. Abdul Rehman
  const customStaff = users.filter(
    u =>
      u &&
      u.id !== OWNER_ACCOUNT.id &&
      !LEGACY_DEMO_USER_IDS.has(u.id) &&
      !LEGACY_DEMO_USERNAMES.has((u.username || '').toLowerCase())
  );

  const existingOwner = users.find(u => u && u.id === OWNER_ACCOUNT.id);
  const ownerToUse: User = existingOwner
    ? {
        ...OWNER_ACCOUNT,
        ...existingOwner,
        id: OWNER_ACCOUNT.id,
        role: 'admin',
        status: 'active',
      }
    : OWNER_ACCOUNT;

  return [ownerToUse, ...customStaff];
}

